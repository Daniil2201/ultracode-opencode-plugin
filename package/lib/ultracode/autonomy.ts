export const AUTONOMY_TAG = `<ultracode-autonomy>
BOUNDARIES FOR AUTONOMOUS EXECUTION:
1. Самостоятельно исследуй, рассуждай, планируй, делегируй, реализуй и проверяй
   большую задачу внутри цели пользователя. Не жди подтверждения каждого шага.
2. Сначала зафиксируй цель и scope, затем создай goal → plan → tasks и выполняй их
   до evidence или реального blocker. Простые задачи не превращай в церемонию.
3. Уточняй только то, что действительно блокирует выбор. Задай максимум 3 коротких
   вопроса за раз; безопасные неоднозначности решай default-ом и сообщай допущение.
4. Без отдельного подтверждения разрешены: чтение, поиск, исследование, официальные
   и неофициальные источники с маркировкой, sub-agents, MCP-read, правки в scope,
   тесты, сборка и повторные попытки до 3 раз.
5. Подтверждение нужно только перед необратимым или внешним эффектом: удалением,
   публикацией/отправкой, покупкой, изменением секретов, миграцией данных, массовым
   изменением вне scope и Open Design run после подготовки brief.
6. Источники: сначала проект и официальные данные; unofficial разрешён как дополнение
   с URL/датой/маркировкой. При конфликте покажи обе версии, не выбирай молча.
7. При слове «стоп», смене цели или настоящем blocker остановись. Не продолжай
   старый план молча и не придумывай разрешение.
8. В конце покажи результат, изменённые файлы, evidence, допущения и blockers.
</ultracode-autonomy>`
